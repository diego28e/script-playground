// Writes lib/compass/detector-source.ts: lib/compass/detector.py as a string, for the platform to run with a learner's
// code on the grader (the scratchbook's "concepts in your code", docs/compass.md). The Python file stays the one source
// of truth; run this after changing it. Its command-line block (`if __name__ == "__main__":`) is left out: on the
// grader the module runs as __main__ and would read stdin.
//
//   npx tsx scripts/compass-detector-source.ts
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const root = join(__dirname, "..");
const source = readFileSync(join(root, "lib/compass/detector.py"), "utf8").replace(/\r\n/g, "\n");
const cut = source.indexOf('\nif __name__ == "__main__":');
if (cut < 0) throw new Error('detector.py has no `if __name__ == "__main__":` block to leave out');
const module = source.slice(0, cut).trimEnd() + "\n";
writeFileSync(
  join(root, "lib/compass/detector-source.ts"),
  `// Generated by scripts/compass-detector-source.ts from lib/compass/detector.py: don't edit, regenerate.\nexport const DETECTOR_SOURCE = ${JSON.stringify(module)};\n`,
);
console.log(`lib/compass/detector-source.ts: ${module.length} characters`);
